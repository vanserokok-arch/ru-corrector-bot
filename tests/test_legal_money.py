@pytest.mark.parametrize(
    "src",
    [
        "в срок 5 дней",
        "договор № B55-77/2023",
        "01.02.2023",
        "ст. 10 ГК РФ",
        "номер документа 12345",
    ],
)
def test_normalize_money_does_not_touch_non_money_numbers(src):
    assert normalize_money(src) == src


def test_detect_money_entities_contextual_amount():
    spans = detect_money_entities("убытки 250000")
    assert spans == [
        MoneySpan(
            start=0,
            end=len("убытки 250000"),
            rubles=250000,
            context="убытки",
            needs_v_razmere=True,
            source="убытки 250000",
        )
    ]


def test_detect_money_entities_explicit_amount():
    spans = detect_money_entities("Оплата 120000р произведена")
    assert len(spans) == 1
    assert spans[0].rubles == 120000
    assert spans[0].has_currency_marker is True
    assert spans[0].needs_v_razmere is False


def test_detect_money_entities_verb_window_amount():
    spans = detect_money_entities("прошу взыскать задолженность 40000")
    assert spans
    assert spans[0].rubles == 40000
    assert spans[0].context
    assert "взыскать" in spans[0].context.lower()
